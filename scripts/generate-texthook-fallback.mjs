// Pin the emergency GitHub download to committed bytes, independent of R2.
// Usage: node scripts/generate-texthook-fallback.mjs <published-git-ref>
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const repoRoot = fileURLToPath(new URL('../', import.meta.url));
const ref = process.argv[2];
if (!ref) throw new Error('Supply a published Git revision containing the manifest and engine binaries.');
const git = (...args) => execFileSync('git', args, { cwd: repoRoot, maxBuffer: 32 * 1024 * 1024 });
const revision = git('rev-parse', '--verify', `${ref}^{commit}`).toString().trim();
const manifest = JSON.parse(git('show', `${revision}:texthook_manifest.json`).toString());
const fallback = {
    revision,
    version: manifest.version,
    files: manifest.files.map(({ path }) => ({
        path,
        // Hash Git blobs, not the working tree: text files can differ from R2.
        sha256: createHash('sha256')
            .update(git('show', `${revision}:electron-src/assets/texthook/${path}`))
            .digest('hex'),
    })),
};
const output = new URL('../electron-src/main/ui/texthook_fallback_manifest.ts', import.meta.url);
writeFileSync(output, `// Generated by scripts/generate-texthook-fallback.mjs from committed Git blobs.\nexport default ${JSON.stringify(fallback, null, 2)};\n`);
console.log(`Pinned texthook fallback v${fallback.version} to ${revision} (${fallback.files.length} files).`);
