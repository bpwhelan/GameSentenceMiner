pub fn profile_language_name(code: &str) -> &'static str {
    names(code).map_or("Unknown", |(name, _)| name)
}

pub fn language_display_name(code: &str) -> &'static str {
    let trimmed = code.trim();
    if let Some((_, display)) = names(trimmed) {
        return display;
    }
    names(&trimmed.to_ascii_lowercase()).map_or("English", |(_, display)| display)
}
